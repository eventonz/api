/**
 * Provision the Evento splits feed directly by RaceResult event id + org id,
 * for events that have no v2.races row yet (e.g. our own test event 154651).
 *
 * Same service path as POST /v2/raceresult/provision/:race_id, minus the
 * database lookups and the v2.races write. Still gated by RR_ALLOW_WRITES.
 *
 * Usage:
 *   node scripts/rr-provision-by-event.js <rr_event_id> <org_id> [--write]
 */
require('dotenv').config();

const pool = require('../src/config/database');
const redis = require('../src/config/redis');
const rr = require('../src/services/raceresult/orgApi');
const { buildListData, coverageGaps } = require('../src/services/raceresult/listTemplate');
const { LIST_NAME, SIMPLE_API_LABEL, verifyFeed } = require('../src/services/raceresult/provision');

const listUrl = (name) => `lists/create?listname=${encodeURIComponent(name)}&format=JSON`;

(async () => {
  const rrEventId = Number(process.argv[2]);
  const orgId = Number(process.argv[3]);
  const doWrite = process.argv.includes('--write');
  if (!rrEventId || !orgId) {
    throw new Error('usage: node scripts/rr-provision-by-event.js <rr_event_id> <org_id> [--write]');
  }

  const token = await rr.tokenForOrg(orgId);
  const splits = await rr.getAllSplits(token, rrEventId);
  const { data, names, blocks, hash } = buildListData(splits);

  console.log(`event ${rrEventId} · org ${orgId}`);
  console.log('split rows:', splits.length, '· blocks:', blocks);
  console.log('names:', names.join(', '));
  console.log('template bytes:', data.length, '· hash:', hash);

  const publicCfg = await rr.getPublicConfig(rrEventId).catch(() => null);
  if (publicCfg) {
    const gaps = coverageGaps(names, publicCfg.splits || []);
    console.log('coverage gaps:', gaps.length ? gaps.map((g) => g.name).join(', ') : 'none');
  }

  if (!doWrite) {
    console.log('\n(dry run — pass --write to create the list)');
    await pool.end(); await redis.quit().catch(() => {});
    return;
  }

  const existing = await rr.getLists(token, rrEventId).catch(() => []);
  if (!(Array.isArray(existing) && existing.includes(LIST_NAME))) {
    console.log('creating list:', LIST_NAME);
    await rr.createList(token, rrEventId, LIST_NAME);
  } else {
    console.log('list already exists, replacing body:', LIST_NAME);
  }

  const base = await rr.getList(token, rrEventId, LIST_NAME);
  await rr.saveList(token, rrEventId, {
    ...base,
    ListName: LIST_NAME,
    Fields: [{ ...(base.Fields?.[0] || {}), Expression: data, Label: '', Line: 1 }],
    Filters: [{ OrConjunction: false, Expression1: 'Contest', Operator: '>', Expression2: '0' }],
    Orders: [],
    Remarks: 'Generated by Evento — do not edit.',
  });
  console.log('list saved');

  // Reuse an existing Evento key on this event so the URL stays stable.
  const api = await rr.getSimpleApi(token, rrEventId).catch(() => []);
  const mine = (Array.isArray(api) ? api : []).find((i) => i.Label === SIMPLE_API_LABEL);
  const key = mine?.Key || rr.mintSimpleApiKey();

  await rr.saveSimpleApi(token, rrEventId, [
    { Disabled: false, Key: key, Label: SIMPLE_API_LABEL, URL: listUrl(LIST_NAME) },
  ]);
  const url = rr.simpleApiUrl(rrEventId, key);
  console.log('simple api key saved →', url);

  console.log('verifying…');
  console.log('verification:', JSON.stringify(await verifyFeed(url), null, 1));

  await pool.end();
  await redis.quit().catch(() => {});
})().catch((e) => { console.error('FAILED:', e.message); process.exit(1); });
